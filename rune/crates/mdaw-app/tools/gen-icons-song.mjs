#!/usr/bin/env node
// Generates src/icons_song.rs: the lucide icons the Electron app uses (lucide-react, ISC), as Rune
// `Icon` SVG bodies. Run from the repo root: node rune/crates/mdaw-app/tools/gen-icons-song.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const pkgDir = require.resolve('lucide-react/package.json', { paths: [process.cwd()] }).replace(/package\.json$/, '');
const version = JSON.parse(readFileSync(pkgDir + 'package.json', 'utf8')).version;
const NAMES = [
  'zoom-in', 'zoom-out', 'mouse-pointer-2', 'flag', 'magnet', 'activity', 'arrow-left', 'circle-help',
  'fold-vertical', 'unfold-vertical', 'grid-3x3', 'locate-fixed', 'pencil',
];
const _PHASE7 = [
  'maximize-2', 'minimize-2', 'undo-2', 'redo-2', 'panel-left', 'sliders-horizontal', 'music', 'audio-lines',
  'folder-open', 'plus', 'file-up', 'settings', 'terminal', 'package', 'keyboard', 'settings-2', 'circle',
  'download', 'play', 'square', 'scissors', 'repeat', 'trash-2', 'check', 'chevron-down', 'chevron-up',
  'chevron-right', 'drum', 'package-x', 'triangle-alert', 'eraser', 'replace', 'x', 'rotate-cw', 'zap', 'piano',
  'volume-2', 'volume-x', 'refresh-cw', 'folder-plus', 'search', 'loader-circle', 'folder', 'file-audio',
  'folder-root', 'hard-drive', 'cable',
];
const FILLED = [];
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
let out = `//! Generated by \`tools/gen-icons-song.mjs\` from lucide-react ${version} (ISC license): the Song view's\n//! extra icons, as Rune SVG icon bodies (24-point view box, 2-point round strokes).\n\nuse rune::Icon;\n\n`;
for (const name of NAMES) {
  let file = name;
  // Renamed icons are aliases: `export { default } from './trash.mjs'`.
  const alias = readFileSync(`${pkgDir}dist/esm/icons/${file}.mjs`, 'utf8').match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
  if (alias) file = alias[1];
  const { __iconData } = await import(`${pkgDir}dist/esm/icons/${file}.mjs`);
  if (!__iconData) throw new Error(`no __iconData in ${name}`);
  const node = __iconData.node;
  const body = node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`)
    .join('');
  const g = `<g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</g>`;
  const ident = name.toUpperCase().replace(/-/g, '_');
  out += `pub static ${ident}: Icon = Icon { name: "${name}", view: 24.0, body: r#"${g}"# };\n`;
  // \`className="fill-current"\` in the app (transport play / stop / record).
  if (FILLED.includes(name)) {
    out += `pub static ${ident}_FILLED: Icon = Icon { name: "${name}-filled", view: 24.0, body: r#"${g.replace('fill="none"', 'fill="currentColor"')}"# };\n`;
  }
}
writeFileSync('rune/crates/mdaw-app/src/icons_song.rs', out);
console.log(`wrote ${NAMES.length} icons`);
