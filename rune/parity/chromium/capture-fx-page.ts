/**
 * Loaded INSIDE the page (Vite dev server, real Tone.js, real Chromium Web Audio) by
 * capture-fx.steps.mjs. Runs a scripted battery through the app's real effect chains:
 *
 * - **strip**: `createTrackAudioNodes` (src/utils/trackAudioFactory.ts) of an audio track whose
 *   input is a generated buffer, driven by the real `ArrangementEngine` code paths:
 *   `applyTrackEffect` (setTrackEffect), `resetTrackEffects` and `scheduleAutomation` (play), and
 *   the `setTrackVolume` / `setTrackPan` / `setTrackMute` node writes.
 * - **live**: a fresh `AudioEngine` (src/services/AudioEngine.ts, `start()`: its FX chain, the
 *   master bus on the context's destination) whose `fxInput` gets the buffer, driven by its
 *   setters.
 *
 * Like capture-sampler-page.ts this drives a native OfflineAudioContext wrapped in a
 * `Tone.OfflineContext` and applies every step with `suspend()` / `resume()` at its quantum,
 * with Tone's clock (`now()`) set to the suspend time (Tone's lookAhead is 0 offline).
 * `scheduleAutomation`'s `transport.schedule` calls are collected (the context's transport is
 * patched) and each callback is invoked at the quantum of its time with that time, as Tone's
 * transport would (the play time is the transport start).
 */
import * as Tone from 'tone';
import { createTrackAudioNodes } from '@/utils/trackAudioFactory';
import { arrangementEngine } from '@/services/ArrangementEngine';
import { audioEngine } from '@/services/AudioEngine';
import type { Track } from '@/types/arrangement';
import type { TrackEffectState } from '@/types/effects';

export type StripOp =
  | { op: 'apply'; name: keyof TrackEffectState; params: Record<string, unknown> }
  | { op: 'play' }
  | { op: 'reset' }
  | { op: 'track'; patch: Partial<Track> }
  | { op: 'pan'; v: number }
  | { op: 'volume'; v: number }
  | { op: 'mute'; m: boolean };

export type LiveOp = { op: string; v: unknown };

export interface Step<O> {
  frame: number;
  ops: O[];
}

export interface Case {
  id: string;
  kind: 'strip' | 'live';
  sr: number;
  frames: number;
  /** Interleaved per channel: [L, R] base64 f32 (generated by the steps script). */
  input: string[];
  track?: Partial<Track>;
  bpm?: number;
  /** live: setters called before `start()` (they only record the params then). */
  init?: LiveOp[];
  steps: Step<StripOp | LiveOp>[];
}

function b64(data: Float32Array): string {
  const bytes = new Uint8Array(data.buffer, data.byteOffset, data.byteLength);
  let s = '';
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) s += String.fromCharCode(...bytes.subarray(i, i + CHUNK));
  return btoa(s);
}

function unb64(s: string): Float32Array {
  const bin = atob(s);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new Float32Array(bytes.buffer);
}

type Priv = Record<string, (...a: unknown[]) => unknown>;

export async function renderCase(c: Case): Promise<{ channels: string[]; log: unknown[] }> {
  const raw = new OfflineAudioContext({ numberOfChannels: 2, length: c.frames, sampleRate: c.sr });
  const ctx = new Tone.OfflineContext(raw);
  const clock = ctx as unknown as { _currentTime: number };
  const prev = Tone.getContext();
  Tone.setContext(ctx);
  const log: unknown[] = [];
  const errors: string[] = [];
  const warn = console.warn;
  try {
    const buf = new AudioBuffer({ length: c.frames, numberOfChannels: 2, sampleRate: c.sr });
    c.input.forEach((d, ch) => buf.copyToChannel(unb64(d), ch));
    const src = new AudioBufferSourceNode(raw, { buffer: buf });
    src.start(0);

    // Callbacks collected from transport.schedule, invoked at their quanta.
    const pending: { time: number; cb: (t: number) => void }[] = [];
    const transport = Tone.getTransport() as unknown as { schedule: (cb: (t: number) => void, t: number) => number };
    let t0 = 0;
    transport.schedule = (cb, t) => {
      pending.push({ time: t0 + t, cb });
      return pending.length;
    };

    let run: (step: Step<StripOp | LiveOp>) => void;
    if (c.kind === 'strip') {
      const track = {
        id: 't',
        name: 't',
        instrument: { type: 'audio', presetIndex: 0 },
        regions: [],
        volume: 0,
        pan: 0,
        muted: false,
        solo: false,
        color: '',
        ...c.track,
      } as unknown as Track;
      const audio = createTrackAudioNodes(track, ctx.destination);
      Tone.connect(src, audio.filter);
      const ae = Object.getPrototypeOf(arrangementEngine) as Priv;
      const self = { arrangement: { bpm: c.bpm ?? 120 } };
      run = (step) => {
        for (const o of step.ops as StripOp[]) {
          switch (o.op) {
            case 'apply': {
              const fx = track.effects![o.name] as Record<string, unknown>;
              Object.assign(fx, o.params);
              ae.applyTrackEffect.call(self, audio, track.effects, o.name);
              break;
            }
            case 'track':
              Object.assign(track, o.patch);
              break;
            case 'reset':
              ae.resetTrackEffects.call(self, track, audio);
              break;
            case 'play':
              t0 = step.frame / c.sr;
              ae.resetTrackEffects.call(self, track, audio);
              ae.scheduleAutomation.call(self, track, audio);
              log.push({ frame: step.frame, automation: pending.length });
              break;
            case 'pan':
              audio.panner.pan.value = o.v;
              break;
            case 'volume':
              audio.volume.volume.value = o.v;
              break;
            case 'mute':
              audio.volume.mute = o.m;
              break;
          }
        }
      };
    } else {
      const eng = new (audioEngine.constructor as new () => typeof audioEngine)();
      const e = eng as unknown as Priv & Record<string, unknown>;
      for (const o of c.init ?? []) e[o.op](o.v);
      console.warn = () => {};
      await eng.start();
      Tone.connect(src, e.fxInput as unknown as Tone.ToneAudioNode);
      run = (step) => {
        for (const o of step.ops as LiveOp[]) e[o.op](o.v);
        log.push({ frame: step.frame, stages: e.activeStages });
      };
      log.push({ frame: 0, stages: e.activeStages });
    }

    // Suspend points: the steps and the quanta of every automation callback (known after
    // the 'play' step ran, so callbacks are chained from inside it).
    const q = (t: number) => Math.floor((t * c.sr + 1e-6) / 128) * 128;
    const fired = new Set<number>();
    const stepAt = new Map(c.steps.map((s) => [s.frame, s]));
    const atFrame = (frame: number) => {
      clock._currentTime = raw.currentTime;
      const s = stepAt.get(frame);
      if (s) run(s);
      for (let i = 0; i < pending.length; i++) {
        if (!fired.has(i) && q(pending[i].time) === frame) {
          fired.add(i);
          pending[i].cb(pending[i].time);
        }
      }
    };
    const frames = new Set<number>(c.steps.map((s) => s.frame));
    let scheduled = new Set<number>();
    const suspendAt = (frame: number) => {
      if (scheduled.has(frame) || frame <= 0 || frame >= c.frames) return;
      scheduled.add(frame);
      void raw.suspend(frame / c.sr).then(async () => {
        try {
          if (Math.round(raw.currentTime * c.sr) !== frame) throw new Error(`suspended at ${raw.currentTime * c.sr}, wanted ${frame}`);
          atFrame(frame);
          for (const p of pending) suspendAt(q(p.time));
        } catch (err) {
          errors.push(`${frame}: ${err instanceof Error ? err.stack : String(err)}`);
        }
        await raw.resume();
      });
    };
    if (frames.has(0)) atFrame(0);
    for (const f of frames) suspendAt(f);
    for (const p of pending) suspendAt(q(p.time));
    const rendered = await raw.startRendering();
    if (errors.length) throw new Error(errors.join('\n'));
    log.push({ automationFired: fired.size, automationTotal: pending.length });
    return { channels: [b64(rendered.getChannelData(0)), b64(rendered.getChannelData(1))], log };
  } finally {
    console.warn = warn;
    Tone.setContext(prev);
  }
}
